use serde_json::Value;
use std::collections::BTreeSet;
use std::fs;
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn text(path: &str) -> String {
    fs::read_to_string(root().join(path)).unwrap_or_else(|error| panic!("{path}: {error}"))
}

fn json(path: &str) -> Value {
    serde_json::from_str(&text(path)).unwrap_or_else(|error| panic!("{path}: {error}"))
}

#[test]
fn manifest_registers_one_menu_item_with_playground_and_demo_tabs() {
    let manifest = json("ui/manifest.json");
    assert_eq!(manifest["schema"], "pom-plugin-ui/v1");
    assert_eq!(manifest["plugin_code"], "jev");
    assert_eq!(manifest["icon_image"], "ui/icon.png");
    let menu = manifest["menu"].as_array().expect("menu");
    assert_eq!(menu.len(), 1);
    assert_eq!(menu[0]["label"]["en"], "POM-JEV");
    assert_eq!(menu[0]["to"], "/jev");
    assert!(menu[0].get("children").is_none());
    let routes = manifest["routes"].as_array().unwrap();
    assert_eq!(routes.len(), 1);
    assert_eq!(routes[0]["path"], "/jev");
    assert_eq!(routes[0]["screen"], "jev");
    assert_eq!(routes[0]["full_bleed"], true);
    assert_eq!(manifest["screens"]["jev"]["export"], "jev");
    assert_eq!(manifest["screens"]["jev"]["module"], "ui/screens.js");
    assert!(text("ui/src/screens/index.tsx").contains("JevApp as jev"));
    let app = text("ui/src/screens/JevApp.tsx");
    assert!(app.contains("<Playground />") && app.contains("<Demo />"));
}

